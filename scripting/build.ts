/**
 * Bundles shared/main.ts, server/main.ts and client/main.ts into independent plain
 * scripts under dist/<name> (Jint has no ES-module loader).
 *
 *   bun run build.ts                 # build all
 *   bun run build.ts hello           # build one
 *   bun run build.ts --deploy <dir>  # build all and copy into <dir>/<name>
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, copyFileSync, cpSync } from "node:fs";
import { join, resolve } from "node:path";

const here = import.meta.dir;
let pluginsDir = join(here, "plugins");
let distDir = join(here, "dist");
let tmpDir = join(distDir, ".tmp");

const argv = process.argv.slice(2);
let deployRoot: string | null = null;
const names: string[] = [];

for (let index = 0; index < argv.length; index++) {
    const arg = argv[index];
    if (arg === "--deploy") {
        deployRoot = resolve(argv[++index] ?? "");
    } else if (arg === "--source") {
        pluginsDir = resolve(argv[++index] ?? "");
    } else if (arg === "--out") {
        distDir = resolve(argv[++index] ?? "");
        tmpDir = join(distDir, ".tmp");
    } else if (!arg.startsWith("-")) {
        names.push(arg);
    }
}

const all = readdirSync(pluginsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name);

const targets = names.length > 0 ? names : all;
for (const name of targets) {
    if (!all.includes(name)) throw new Error(`Unknown plugin directory: ${name}`);
}

// dist is a mirror of plugins/: anything not built this run must not survive, or a deleted
// plugin would keep deploying forever.
if (names.length === 0 && existsSync(distDir)) {
    rmSync(distDir, { recursive: true, force: true });
}

if (targets.length === 0) {
    // An empty plugins folder is a valid state (the runtime ships without examples).
    console.log("no plugins to bundle");
    process.exit(0);
}

mkdirSync(tmpDir, { recursive: true });

let failed = false;

/** Entries built per plugin: shared, plus optional side-specific bundles. */
const ENTRIES: Array<{ source: string; side: string }> = [
    { source: "shared/main.ts", side: "shared" },
    { source: "server/main.ts", side: "server" },
    { source: "client/main.ts", side: "client" }
];

for (const name of targets) {
    const sourceDir = join(pluginsDir, name);
    const outdir = join(distDir, name);
    rmSync(outdir, { recursive: true, force: true });

    const built: string[] = [];
    let pluginFailed = false;
    for (const entry of ENTRIES) {
        const source = join(sourceDir, entry.source);
        if (!existsSync(source)) {
            continue;
        }

        // A generated entry keeps the plugin source a normal ES module while the emitted
        // bundle stays a plain script that only mutates a global.
        const wrapper = join(tmpDir, `${name}-${entry.side}.entry.ts`);
        writeFileSync(
            wrapper,
            `import plugin from ${JSON.stringify(source.replaceAll("\\", "/"))};\n` +
            `(globalThis as { __vjs_plugin?: unknown }).__vjs_plugin = plugin;\n`,
            "utf8"
        );

        const targetDir = outdir;
        const result = await Bun.build({
            entrypoints: [wrapper],
            outdir: targetDir,
            target: "browser",
            format: "iife",
            naming: `${entry.side}.js`,
            minify: false,
            sourcemap: "none",
            define: { "process.env.NODE_ENV": JSON.stringify("production") }
        });

        if (!result.success) {
            console.error(`✗ ${name} (${entry.source})`);
            for (const log of result.logs) {
                console.error("  " + log);
            }
            failed = true;
            pluginFailed = true;
            continue;
        }

        const bundlePath = join(targetDir, `${entry.side}.js`);
        const code = readFileSync(bundlePath, "utf8");
        if (/^\s*(import|export)\s/m.test(code)) {
            console.error(`✗ ${name} (${entry.source}): bundle still contains ESM syntax`);
            failed = true;
            pluginFailed = true;
            continue;
        }

        built.push(`${entry.side} ${(code.length / 1024).toFixed(1)} KiB`);
    }

    if (built.length === 0) {
        console.error(`✗ ${name}: no entry (shared/main.ts, server/main.ts or client/main.ts)`);
        failed = true;
        pluginFailed = true;
    }
    if (pluginFailed) {
        rmSync(outdir, { recursive: true, force: true });
        continue;
    }

    const manifestSource = join(sourceDir, "manifest.ini");
    const manifestTarget = join(outdir, "manifest.ini");
    if (existsSync(manifestSource)) {
        copyFileSync(manifestSource, manifestTarget);
    } else {
        writeFileSync(
            manifestTarget,
            `# generated by build.ts\nname=${name}\nversion=0.0.1\napiVersion=1\nenabled=true\n`,
            "utf8"
        );
    }

    console.log(`✓ ${name} → ${outdir} (${built.join(", ")})`);

    if (deployRoot) {
        const destination = join(deployRoot, name);
        // name was checked against immediate source directories before any removals.
        rmSync(destination, { recursive: true, force: true });
        mkdirSync(destination, { recursive: true });
        cpSync(outdir, destination, { recursive: true, force: true });
        console.log(`  deployed → ${destination}`);
    }
}

rmSync(tmpDir, { recursive: true, force: true });
process.exit(failed ? 1 : 0);
