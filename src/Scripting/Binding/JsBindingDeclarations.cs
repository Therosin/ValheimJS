using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace ValheimJS.Scripting.Binding;

/// <summary>
/// Renders the validated binding catalog as a TypeScript module. The output is checked in and
/// verified for drift, so declarations can never disagree with the methods scripts actually get.
/// </summary>
public static class JsBindingDeclarations
{
    private static readonly Regex DeclaredTypePattern = new(@"\b([A-Z][A-Za-z0-9_]*)\b", RegexOptions.Compiled);

    private static readonly HashSet<string> ReservedTypeNames = new(StringComparer.Ordinal)
    {
        "Record", "Promise", "Array", "ReadonlyArray", "Map", "Set", "Date", "Error", "String",
        "Number", "Boolean", "Object", "Function", "JSON"
    };

    public static string Write(JsBindingCatalog catalog)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated>");
        builder.AppendLine("// Generated from [JsBinder]/[JsBinding] metadata by `task declarations`.");
        builder.AppendLine("// Do not edit by hand; run `task declarations:check` to verify drift.");
        builder.AppendLine("// </auto-generated>");
        builder.AppendLine();

        var imported = ImportedTypes(catalog);
        if (imported.Count > 0)
        {
            builder.AppendLine("import type { " + string.Join(", ", imported) + " } from \"./types\";");
            builder.AppendLine();
        }

        foreach (var binder in catalog.Binders)
        {
            AppendBinder(builder, binder);
        }

        builder.AppendLine("/** Everything the C# binding classes install under `ctx.host.api`. */");
        builder.AppendLine("export interface Api {");
        foreach (var binder in catalog.Binders)
        {
            var availability = DescribeAvailability(binder.Availability);
            if (availability != null)
            {
                builder.AppendLine($"    /** Availability: {availability}. */");
            }

            builder.AppendLine($"    {binder.Namespace}: {InterfaceName(binder.Namespace)};");
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    private static void AppendBinder(StringBuilder builder, JsBinderMetadata binder)
    {
        if (!string.IsNullOrWhiteSpace(binder.Description))
        {
            builder.AppendLine("/**");
            AppendDocLines(builder, binder.Description!, " * ");
            var availability = DescribeAvailability(binder.Availability);
            if (availability != null)
            {
                builder.AppendLine($" * @availability {availability}");
            }

            builder.AppendLine(" */");
        }
        else
        {
            var availability = DescribeAvailability(binder.Availability);
            if (availability != null)
            {
                builder.AppendLine($"/** @availability {availability} */");
            }
        }

        builder.AppendLine($"export interface {InterfaceName(binder.Namespace)} {{");
        foreach (var method in binder.Methods)
        {
            AppendMethod(builder, method);
        }

        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static void AppendMethod(StringBuilder builder, JsMethodMetadata method)
    {
        var availability = DescribeAvailability(method.Availability);
        var hasDoc = !string.IsNullOrWhiteSpace(method.Description) || availability != null;

        if (hasDoc)
        {
            builder.AppendLine("    /**");
            if (!string.IsNullOrWhiteSpace(method.Description))
            {
                AppendDocLines(builder, method.Description!, "     * ");
            }

            if (availability != null)
            {
                builder.AppendLine($"     * @availability {availability}");
            }

            builder.AppendLine("     */");
        }

        var parameters = string.Join(", ", method.Parameters.Select(parameter =>
            $"{parameter.Name}: {parameter.Type.ToTypeScript()}"));
        builder.AppendLine($"    {method.Name}({parameters}): {method.ReturnType.ToTypeScript()};");
    }

    private static IReadOnlyList<string> ImportedTypes(JsBindingCatalog catalog)
    {
        var names = new SortedSet<string>(StringComparer.Ordinal);
        foreach (var binder in catalog.Binders)
        {
            foreach (var method in binder.Methods)
            {
                Collect(method.ReturnType, names);
                foreach (var parameter in method.Parameters)
                {
                    Collect(parameter.Type, names);
                }
            }
        }

        return names.ToList();
    }

    private static void Collect(JsTypeRef type, ISet<string> names)
    {
        if (string.IsNullOrEmpty(type.DeclaredText))
        {
            return;
        }

        foreach (Match match in DeclaredTypePattern.Matches(type.DeclaredText!))
        {
            var name = match.Groups[1].Value;
            if (!ReservedTypeNames.Contains(name))
            {
                names.Add(name);
            }
        }
    }

    private static void AppendDocLines(StringBuilder builder, string text, string prefix)
    {
        foreach (var line in text.Replace("\r\n", "\n").Split('\n'))
        {
            builder.AppendLine(prefix + line.Replace("*/", "* /").TrimEnd());
        }
    }

    private static string InterfaceName(string nameSpace) =>
        char.ToUpperInvariant(nameSpace[0]) + nameSpace.Substring(1) + "Api";

    private static string? DescribeAvailability(JsAvailability availability)
    {
        if (availability == JsAvailability.Always)
        {
            return null;
        }

        var parts = new List<string>();
        if ((availability & JsAvailability.Dedicated) != 0)
        {
            parts.Add("dedicated server only");
        }

        if ((availability & JsAvailability.Server) != 0)
        {
            parts.Add("server authority only");
        }

        if ((availability & JsAvailability.Client) != 0)
        {
            parts.Add("client only");
        }

        return parts.Count == 0 ? null : string.Join(", ", parts);
    }
}
